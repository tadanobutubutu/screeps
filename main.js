function addLangAttribute(lang = 'en') {
  const doc = getDocument();
  if (doc && doc.documentElement) {
    if (doc.documentElement.lang !== lang) {
      doc.documentElement.setAttribute('lang', getFullLangAttribute(lang));
    }
  }
}

