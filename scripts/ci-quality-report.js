#!/usr/bin/env node
/**
 * CircleCI Weekly Quality Report Generator
 */
const { execSync } = require('child_process');
const fs = require('fs');

const now = new Date();
const weekAgo = new Date(now - 7 * 24 * 60 * 60 * 1000);

let report = `# 📊 Weekly Quality Report\n\n`;
report += `**Period**: ${weekAgo.toISOString().slice(0,10)} ~ ${now.toISOString().slice(0,10)}\n`;
report += `**Generated**: ${now.toISOString()}\n\n---\n\n`;

// File stats
try {
  const jsFiles = execSync("find . -name '*.js' -not -path './node_modules/*' -not -path './.git/*' | wc -l").toString().trim();
  const totalLines = execSync("find . -name '*.js' -not -path './node_modules/*' -not -path './.git/*' -exec wc -l {} + | tail -1 | awk '{print $1}'").toString().trim();
  report += `## 📁 Code Stats\n\n- JS Files: ${jsFiles}\n- Total Lines: ${totalLines}\n\n`;
} catch(e) { report += `## 📁 Code Stats\n\n⚠️ Error collecting stats\n\n`; }

// Test results
try {
  execSync('npx jest --passWithNoTests --json 2>/dev/null > /tmp/test-results.json', { stdio: 'pipe' });
  const results = JSON.parse(fs.readFileSync('/tmp/test-results.json', 'utf8'));
  report += `## 🧪 Test Results\n\n`;
  report += `- Total: ${results.numTotalTests}\n`;
  report += `- Passed: ${results.numPassedTests}\n`;
  report += `- Failed: ${results.numFailedTests}\n\n`;
} catch(e) { report += `## 🧪 Test Results\n\n⚠️ No test data available\n\n`; }

// Dependency check
try {
  const outdated = execSync('pnpm outdated --format json 2>/dev/null || echo "[]"').toString().trim();
  report += `## 📦 Dependencies\n\n`;
  report += `See \`pnpm outdated\` for details.\n\n`;
} catch(e) { /* skip */ }

report += `---\n\n*Auto-generated by CircleCI Weekly Quality Report*\n`;
fs.writeFileSync('WEEKLY_QUALITY_REPORT.md', report);
console.log('✅ Report generated');
