function fetchUser(userId) {
  // Fetch user implementation
  const cachedUser = appState.cache.get(userId);
  if (cachedUser) {
    return cachedUser;
  }
  
  const user = {
    id: userId,
    name: `User ${userId}`,
    createdAt: new Date().toISOString()
  };
  
  appState.cache.set(userId, user);
  appState.users.push(user);
  return user;
}

