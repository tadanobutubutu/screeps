  const buttonsWithRoleButton = document.querySelectorAll('[role="button"]');
  buttonsWithRoleButton.forEach(function(button) {
    button.addEventListener('keydown', function(e) {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        this.click();
      }
    });
  });
