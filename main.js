function fixFakeLinksWithArray(links) {
  if (!Array.isArray(links)) return [];
  return links.map(link => {
    if (link.href && !link.getAttribute('role')) {
      if (link.href.startsWith('#') || link.href === '') {
        link.setAttribute('role', 'button');
      }
    }
    return link;
  });
}

