/**
 * Main application entry point
 * Handles generation of accessible HTML with proper landmarks
 */

// Configuration
const config = {
  title: 'Quality & Metrics Reports',
  outputDir: './docs'
};

// Generate accessible HTML structure with main landmarks
function generateAccessibleHTML(content) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${config.title}</title>
</head>
<body>
    <header>
        <h1>Repository</h1>
    </header>
    <main>
        ${content}
    </main>
    <footer>
        <p>Generated by automated tools</p>
    </footer>
</body>
</html>`;
}

// Generate quality metrics report section
function generateMetricsSection() {
  return `
        <div class="container">
            <h2>Quality & Metrics Reports</h2>
            <p>
                This repository is fully optimized with automated tools. Explore the generated
                reports below:
            </p>
            <div class="links">
                <a href="plato.html">Plato Code Complexity Report</a>
                <a href="dependency-graph.html">Dependency Graph</a>
            </div>
        </div>
  `;
}

// Generate data table with proper structure
function generateDataTable(data) {
  if (!data || !data.length) {
    return '<p>No data available</p>';
  }
  
  const headers = Object.keys(data[0]);
  const headerRow = headers.map(h => `<th>${h}</th>`).join('');
  const rows = data.map(item => 
    `<tr>${headers.map(h => `<td>${item[h]}</td>`).join('')}</tr>`
  ).join('');
  
  return `
    <table id="table-rotated">
      <thead>
        <tr>${headerRow}</tr>
      </thead>
      <tbody>
        ${rows}
      </tbody>
    </table>
  `;
}

// Main index generation with all sections wrapped in main
function generateIndex() {
  const metricsSection = generateMetricsSection();
  const tableSection = generateDataTable([]);
  
  return generateAccessibleHTML(`
    <section class="metrics">
        ${metricsSection}
    </section>
    <section class="data-table">
        ${tableSection}
    </section>
  `);
}

// Export functions for use elsewhere
module.exports = {
  config,
  generateAccessibleHTML,
  generateMetricsSection,
  generateDataTable,
  generateIndex
};

// Run if executed directly
if (require.main === module) {
  const fs = require('fs');
  const path = require('path');
  
  const html = generateIndex();
  const outputPath = path.join(config.outputDir, 'index.html');
  
  fs.writeFileSync(outputPath, html);
  console.log(`Generated accessible HTML at ${outputPath}`);
}