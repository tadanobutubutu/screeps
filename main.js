class ErrorBoundary extends React.Component {
    constructor(props) {
        super(props)
        this.state = {
            error: null,
            errorInfo: null,
            hasError: false
        }
        this.handleReload = this.handleReload.bind(this)
    }

    static getDerivedStateFromError(error) {
        return { hasError: true }
    }

    componentDidCatch(error, errorInfo) {
        this.setState({
            error: error,
            errorInfo: errorInfo
        })
    }

    componentDidMount() {
        const unrotateBtn = document.getElementById('unrotate-btn')
        if (unrotateBtn) {
            unrotateBtn.addEventListener('click', handleUnrotate)
        }
    }

    componentWillUnmount() {
        const unrotateBtn = document.getElementById('unrotate-btn')
        if (unrotateBtn) {
            unrotateBtn.removeEventListener('click', handleUnrotate)
        }
    }

    handleReload() {
        window.location.reload()
    }

    render() {
        if (this.state.hasError) {
            return (
                <section
                    role="alert"
                    aria-labelledby="error-heading"
                    style={{ padding: '2rem', fontFamily: 'monospace' }}
                >
                    <h1 id="error-heading" style={{ color: '#b71c1c' }}>⚠️ エラー</h1>
                    <div
                        tabIndex={0}
                        role="region"
                        aria-label="エラーメッセージ詳細"
                        style={{
                            color: '#c53030',
                            backgroundColor: '#fff5f5',
                            padding: '1rem',
                            borderRadius: '4px',
                            overflow: 'auto',
                        }}
                    >
                        <p>{this.state.error && this.state.error.toString()}</p>
                        <p>{this.state.errorInfo && this.state.errorInfo.componentStack}</p>
                    </div>
                    <button
                        id="reload-btn"
                        onClick={this.handleReload}
                        style={{
                            backgroundColor: '#004b73',
                            color: 'white',
                            padding: '0.5rem 1rem',
                            border: 'none',
                            borderRadius: '4px',
                            cursor: 'pointer',
                        }}
                        aria-label="ページを再読み込み"
                    >
                        🔄 ページを再読み込み
                    </button>
                </section>
            )
        }

        return this.props.children
    }
}

