// Add helper function for accessible tables (REACT_027)
export const renderAccessibleTable = (headers: string[], rows: any[][], caption?: string) => {
  return (
    <table>
      {caption && <caption>{caption}</caption>}
      <thead>
        <tr>
          {headers.map((header, index) => (
            <th key={index} scope="col">
              {header}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.map((row, rowIndex) => (
          <tr key={rowIndex}>
            {row.map((cell, cellIndex) => (
              <td key={cellIndex}>{cell}</td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  );
};

// Add helper function for accessible SVG (REACT_041)
export const AccessibleSVG = ({
  title,
  description,
  children,
  ...props
}: {
  title: string;
  description: string;
  children: React.ReactNode;
  [key: string]: any;
}) => {
  return (
    <svg aria-hidden="true" focusable="false" {...props}>
      <title>{title}</title>
      <desc>{description}</desc>
      {children}
    </svg>
  );
};

// Add helper function for accessible links (REACT_036)
export const AccessibleLink = ({
  href,
  children,
  ariaLabel,
  ...props
}: {
  href: string;
  children: React.ReactNode;
  ariaLabel?: string;
  [key: string]: any;
}) => {
  return (
    <a href={href} aria-label={ariaLabel} {...props}>
      {children}
    </a>
  );
};

// Add helper function for landmarks (REACT_017, REACT_025)
export const createLandmark = ({
  role,
  ariaLabel,
  children,
  className = '',
}: {
  role: 'main' | 'navigation' | 'complementary' | 'search' | 'contentinfo' | 'banner';
  ariaLabel: string;
  children: React.ReactNode;
  className?: string;
}) => {
  return (
    <section role={role} aria-label={ariaLabel} className={className}>
      {children}
    </section>
  );
};