function createFocusTrap(container, options = {}) {
  let previousActiveElement = null;
  let focusableElements = [];
  let firstFocusableElement = null;
  let lastFocusableElement = null;
  let trapActivate = null;

  const getFocusableElements = (containerEl) => {
    const focusableSelectors = [
      'a[href]',
      'area[href]',
      'button:not([disabled])',
      'input:not([disabled])',
      'select:not([disabled])',
      'textarea:not([disabled])',
      'iframe',
      'object',
      'embed',
      '[tabindex]:not([tabindex="-1"])',
      '[contenteditable]'
    ].join(',');

    return Array.from(containerEl.querySelectorAll(focusableSelectors))
      .filter(el => el.offsetWidth > 0 || el.offsetHeight > 0 || el.getClientRects().length);
  };

  const updateFocusableElements = () => {
    focusableElements = getFocusableElements(container);
    firstFocusableElement = focusableElements[0];
    lastFocusableElement = focusableElements[focusableElements.length - 1];
  };

  const activate = () => {
    previousActiveElement = document.activeElement;
    updateFocusableElements();

    if (firstFocusableElement) {
      firstFocusableElement.focus();
    }

    trapActivate = (e) => {
      if (e.key === 'Tab') {
        if (e.shiftKey) {
          if (document.activeElement === firstFocusableElement) {
            e.preventDefault();
            lastFocusableElement.focus();
          }
        } else {
          if (document.activeElement === lastFocusableElement) {
            e.preventDefault();
            firstFocusableElement.focus();
          }
        }
      }
    };

    document.addEventListener('keydown', trapActivate);
  };

  const deactivate = () => {
    document.removeEventListener('keydown', trapActivate);
    if (previousActiveElement) {
      previousActiveElement.focus();
    }
    previousActiveElement = null;
  };

  return {
    activate,
    deactivate
  };
}

