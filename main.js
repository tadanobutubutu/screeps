function validateTableAccessibility(table) {
  const issues = [];

  if (!table.headers) {
    issues.push('Missing headers attribute');
  }

  if (!table.scope) {
    issues.push('Missing scope attribute');
  }

  // Check for caption (conflict resolved: check for both)
  if (!table.querySelector || !table.querySelector('caption')) {
    issues.push('Missing caption element');
  }

  return {
    success: issues.length === 0,
    issues
  };
}

/**
 * Validates the structure of tables for accessibility
 * @param {Array|Object} tables - Array of table objects or single table element to validate
 * @returns {Object} Validation result with success status and any issues found
 */
function validateTableStructure(tables) {
  const allIssues = [];

  // Handle both single table element and array of tables
  const tableArray = Array.isArray(tables) ? tables : [tables];

  tableArray.forEach((table, index) => {
    // Check for rows
    const rows = table.querySelectorAll ? table.querySelectorAll('tr') : [];
    if (rows.length === 0) {
      allIssues.push({
        tableIndex: index,
        issues: ['Table has no rows']
      });
    }

    // Additional structure validation can be added here
  });

  return {
    success: allIssues.length === 0,
    issues: allIssues
  };
}

// Merge landmark validation logic:
function validateLandmark(element) {
  const issues = [];
  const validLandmarks = ['header', 'nav', 'main', 'aside', 'footer', 'section', 'article'];
  if (!element.tagName) {
    issues.push('Missing tagName');
  } else if (!validLandmarks.includes(element.tagName.toLowerCase())) {
    issues.push(`Invalid landmark: ${element.tagName}`);
  }
  if (!element.hasAttribute('id')) {
    issues.push('Missing id attribute');
  }
  return {
    success: issues.length === 0,
    issues
  };
}

// Merge landmark validation logic:
function validateLandmarkStructure() {
  const problems = [];

  // If no landmarks array provided, query the DOM
  const allLandmarks = document.querySelectorAll('[role]');
  let hasMain = false;
  let hasNavigation = false;

  allLandmarks.forEach(landmark => {
    const role = landmark.getAttribute('role');
    if (role === 'main') hasMain = true;
    if (role === 'navigation') hasNavigation = true;
  });

  if (!hasMain) {
    problems.push('Missing main landmark');
  }
  if (!hasNavigation) {
    problems.push('Missing navigation landmark');
  }
  return {
    success: problems.length === 0,
    problems
  };
}

// Ensure all landmarks have unique accessible names
function ensureUniqueLandmarks() {
  const names = [];
  const duplicates = [];

  // If landmarks array is provided, validate each one
  let elementsToCheck = [];
  const allLandmarks = document.querySelectorAll('[role]');

  allLandmarks.forEach(landmark => {
    const name = landmark.ariaLabel || landmark.ariaLabelledby || landmark.textContent;
    if (names.includes(name)) {
      duplicates.push(name);
    } else {
      names.push(name);
    }
  });

  // Check for duplicate IDs
  const elementsById = {};
  elementsToCheck = allLandmarks;

  elementsToCheck.forEach(landmark => {
    if (landmark.id) {
      if (elementsById[landmark.id]) {
        duplicates.push(`Duplicate ID: ${landmark.id}`);
        landmark.id += '_duplicate';
      } else {
        elementsById[landmark.id] = true;
      }
    }
  });

  // Check for duplicate roles
  const landmarksByRole = {};
  elementsToCheck = allLandmarks;

  elementsToCheck.forEach(landmark => {
    const role = landmark.getAttribute('role');
    if (role) {
      if (landmarksByRole[role]) {
        duplicates.push(`Duplicate landmark role: ${role}`);
      } else {
        landmarksByRole[role] = true;
      }
    }
  });

  return {
    success: duplicates.length === 0,
    duplicates
  };
}

