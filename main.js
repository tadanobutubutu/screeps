// Add helper function for accessible tables (REACT_027)
export const renderAccessibleTable = (headers: string[], rows: any[][]) => {
  return (
    <table>
      <thead>
        <tr>
          {headers.map((header, index) => (
            <th key={index} scope="col">
              {header}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.map((row, rowIndex) => (
          <tr key={rowIndex}>
            {row.map((cell, cellIndex) => (
              <td key={cellIndex}>{cell}</td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  );
};

// Add helper function for accessible SVG (REACT_041)
export const AccessibleSVG = ({
  title,
  description,
  children,
}: {
  title: string;
  description: string;
  children: React.ReactNode;
}) => {
  return (
    <svg aria-hidden="true" focusable="false">
      <title>{title}</title>
      <desc>{description}</desc>
      {children}
    </svg>
  );
};

// Add helper function for accessible links (REACT_036)
export const AccessibleLink = ({
  href,
  children,
  onClick,
  ...props
}: {
  href: string;
  children: React.ReactNode;
  onClick?: () => void;
  [key: string]: any;
}) => {
  if (href === '#') {
    return (
      <button
        onClick={onClick}
        {...props}
        style={{ background: 'none', border: 'none', padding: 0, cursor: 'pointer', ...props.style }}
      >
        {children}
      </button>
    );
  }

  return (
    <a href={href} {...props}>
      {children}
    </a>
  );
};