// This is a simple greeting module
function greet(name) {
  return `Hello, ${name}!`;
}

// New function to calculate the average of two numbers
export function calculateAverage(a, b) {
  return (a + b) / 2;
}

// Exported functions
export function calculateSum(a, b) {
  return a + b;
}
export function calculateProduct(a, b) {
  return a * b;
}