let taskIdCounter = 0;
const tasks = [];

const addTask = (title, priority = 'medium', tags = []) => {
  taskIdCounter++;
  tasks.push({ id: taskIdCounter, title, priority, tags, completed: false });
  return taskIdCounter;
};

const getTaskById = (taskId) => {
  return tasks.find(task => task.id === taskId) || null;
};

