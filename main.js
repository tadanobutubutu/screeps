// Unique landmarks function
function ensureUniqueLandmarks(landmarks) {
  const seen = new Set();
  if (!landmarks || !Array.isArray(landmarks)) {
    return [];
  }
  return landmarks.filter(landmark => {
    const key = landmark.name + '_' + (landmark.role || 'default');
    if (seen.has(key)) {
      return false;
    }
    seen.add(key);
    return true;
  });
}

