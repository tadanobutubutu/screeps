function ensureUniqueLandmarks(landmarks) {
  if (!Array.isArray(landmarks)) {
    return [];
  }
  const seen = new Set();
  return landmarks.filter(landmark => {
    if (seen.has(`${landmark.id || ''}${landmark.name || ''}`)) {
      return false;
    }
    seen.add(`${landmark.id || ''}${landmark.name || ''}`);
    return true;
  });
}

